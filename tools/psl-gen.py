"""The Public Suffix List (third_party/psl, MPL-2.0) as one glue constant: PSL_RULES, the ICANN and private rules
(Chrome's registry_controlled_domains includes the private ones for sites and cookies), each label converted to its
ASCII (punycode) form, one rule per line. Exceptions keep their leading '!' and wildcards their '*.'."""
import sys
from pathlib import Path

out, src = sys.argv[1], sys.argv[2]
rules = []
for line in Path(src).read_text(encoding="utf-8").splitlines():
    line = line.strip()
    if not line or line.startswith("//"):
        continue
    rule = line.split()[0]
    prefix = ""
    if rule.startswith("!"):
        prefix, rule = "!", rule[1:]
    labels = []
    ok = True
    for label in rule.split("."):
        if label == "*" or label.isascii():
            labels.append(label.lower())
            continue
        try:
            labels.append(label.encode("idna").decode("ascii"))
        except UnicodeError:
            ok = False
            break
    if ok:
        rules.append(prefix + ".".join(labels))
body = "\\n".join(rules)
Path(out).parent.mkdir(parents=True, exist_ok=True)
Path(out).write_text(
    "// Generated by tools/psl-gen.py from third_party/psl/public_suffix_list.dat (Mozilla Public License 2.0,\n"
    "// https://publicsuffix.org). Do not edit.\n"
    f"const PSL_RULES = '{body}';\n")
