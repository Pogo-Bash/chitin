"""The site-compatibility list (docs/surface.md): webcompat/*.json, one rule per file in Ladybird's WebCompat shape, checked and
written as one glue constant (SITE_COMPATIBILITY) that boot() hands to the engine (ganglion_set_site_compatibility).

    tools/webcompat-gen.py OUT.js webcompat/*.json"""
import json
import sys
from pathlib import Path

KEYS = {"matches", "user_agent", "expose_experimental_interfaces"}
TRANSFORMS = {"hide_Chitin"}


def fail(path, why):
    sys.exit(f"{path}: {why}")


def check(path, rule):
    if not isinstance(rule, dict):
        fail(path, "a rule is a JSON object")
    extra = set(rule) - KEYS
    if extra:
        fail(path, f"unknown keys {sorted(extra)}")
    m = rule.get("matches")
    if not isinstance(m, list) or not m or not all(isinstance(p, str) and p for p in m):
        fail(path, "'matches' must be a non-empty array of URL patterns")
    if "user_agent" not in rule and "expose_experimental_interfaces" not in rule:
        fail(path, "a rule needs 'user_agent' or 'expose_experimental_interfaces'")
    if "user_agent" in rule:
        ua = rule["user_agent"]
        if not isinstance(ua, list) or not ua or any(t not in TRANSFORMS for t in ua):
            fail(path, f"'user_agent' must be a non-empty array of {sorted(TRANSFORMS)}")
    if "expose_experimental_interfaces" in rule:
        names = rule["expose_experimental_interfaces"]
        if not isinstance(names, list) or not names or not all(isinstance(n, str) and n for n in names):
            fail(path, "'expose_experimental_interfaces' must be a non-empty array of names")


out, *paths = sys.argv[1:]
rules = []
for p in sorted(paths):
    rule = json.loads(Path(p).read_text())
    check(p, rule)
    rules.append(rule)
Path(out).parent.mkdir(parents=True, exist_ok=True)
Path(out).write_text("// The site-compatibility list (generated by tools/webcompat-gen.py from webcompat/*.json; docs/surface.md).\n"
                     "const SITE_COMPATIBILITY = " + json.dumps(rules, separators=(",", ":")) + ";\n")
