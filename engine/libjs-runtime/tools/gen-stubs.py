# Writes a definition of every function in LibJS/Embedding/ABI.h that traps with its name.
# Ganglion's runtime (engine/libjs-runtime/src) defines the functions it implements, which are left
# out here, so every ABI function exists exactly once and an unimplemented one names
# itself when it is reached instead of failing to link.
import re, sys

abi, out, *sources = sys.argv[1], sys.argv[2], *sys.argv[3:]
text = open(abi).read()
# The functions the runtime defines (extern "C" definitions in its sources) get no stub at all: a weak
# stub seen first would keep the linker from pulling the strong definition out of an archive member.
implemented = set()
for source in sources:
    for line in open(source):
        m = re.search(r'extern "C"[^;]*\bjs_([a-z0-9_]+)\s*\(', line)
        if m and not line.rstrip().endswith(";"):
            implemented.add("js_" + m.group(1))
body = text[text.index('extern "C" {'):]
body = re.sub(r'//[^\n]*', '', body)
decls = re.findall(r'\n([A-Za-z_][^;{}#]*?\b(js_[a-z0-9_]+)\s*\(([^;{}]*?)\))\s*;', body)
lines = [
    "// Generated by engine/libjs-runtime/tools/gen-stubs.py from LibJS/Embedding/ABI.h -- DO NOT EDIT",
    "#include <LibJS/Embedding/ABI.h>",
    "",
    'extern "C" [[noreturn]] void ganglion_js_unimplemented(char const* name);',
    "",
    "#pragma clang diagnostic ignored \"-Wunused-parameter\"",
    "#pragma clang diagnostic ignored \"-Wmissing-prototypes\"",
    'extern "C" {',
]
names = []
for full, name, _ in decls:
    if name in implemented:
        continue
    sig = " ".join(full.split())
    lines.append(f'{sig} {{ ganglion_js_unimplemented("{name}"); }}')
    names.append(name)
lines.append("}")
open(out, "w").write("\n".join(lines) + "\n")
print(f"{len(names)} stubs", file=sys.stderr)
